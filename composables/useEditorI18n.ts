export const useEditorI18n = () => {
  const locale = useState<EditorLocale>('editor-locale', () => 'uk')

  const t = (key: keyof typeof messages.en) => messages[locale.value][key] as string

  const dataSourceOptions = computed(() =>
    dataSourceKeys.map((value) => ({
      value,
      label: messages[locale.value].labels[value]
    }))
  )

  const pagePresetOptions = computed(() => {
    const presetLabels = messages[locale.value].pagePresets
    return (Object.keys(presetLabels) as PagePresetKey[]).map((value) => ({
      value,
      label: presetLabels[value]
    }))
  })

  const localeOptions = [
    { value: 'uk' as const, label: 'Українська' },
    { value: 'en' as const, label: 'English' }
  ]

  const labelForDataSource = (value: DataSourceKey) => messages[locale.value].labels[value]

  return {
    locale,
    t,
    dataSourceOptions,
    pagePresetOptions,
    localeOptions,
    labelForDataSource
  }
}
